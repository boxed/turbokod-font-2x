"""Powerline glyphs (U+E0A0-U+E0BF) at 12x24 for the 24 ppem strike.

The separators are generated by the same formulas as the 16x32 ones (tools/powerline.py)
at 12x24 with 3px strokes: the solid arrow grows 1px per row to the full 12px width on the
two middle rows (a sharp, symmetric tip), the thin arrow is its 3px outer edge, the half
circle is a disc of radius 12 centered on the left edge, and the slants step 1px every 2
rows. All fill the full cell height and tile flush against a full block. The icons are
hand-drawn in glyphs/powerline12x24.txt ('glyph U+XXXX top=N' + rows).
"""
import os

from powerline import separators

W, H, THICKNESS = 12, 24, 3
HAND = os.path.join(os.path.dirname(__file__), "..", "glyphs", "powerline12x24.txt")
_CACHE = None


def load_icons(path=HAND):
    out, cp, top, rows = {}, None, 0, []

    def flush():
        if cp is None:
            return
        assert top + len(rows) <= H, f"U+{cp:04X}: too tall"
        grid = [[False] * W for _ in range(H)]
        for i, row in enumerate(rows):
            assert len(row) == W, f"U+{cp:04X} row {i}: width {len(row)}"
            grid[top + i] = [c == "#" for c in row]
        out[cp] = grid

    for line in open(path):
        line = line.rstrip("\n")
        if line.startswith("glyph "):
            flush()
            _, name, t = line.split()
            cp, top, rows = int(name[2:], 16), int(t[4:]), []
        elif line.strip() and not line.startswith(";"):
            rows.append(line)
    flush()
    return out


def load_12x24():
    """codepoint -> 24-row x 12-col grid of bools, for U+E0A0-U+E0A2 and U+E0B0-U+E0BF."""
    global _CACHE
    if _CACHE is None:
        _CACHE = {**load_icons(), **separators(W, H, THICKNESS)}
    return _CACHE
